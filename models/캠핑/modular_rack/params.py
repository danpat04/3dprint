"""modular_rack 공유 파라미터.

캠핑 박스 테두리에 거는 모듈형 랙: 틀(frame) 하나를 후크로 걸고,
그 안에 유닛 폭 단위 통(bin)을 다양한 조합으로 끼운다.
(spice_rack + cutlery_holder 개념 통합 후속)

  - 기본 유닛 70×70mm. 틀 내부 개구 70×210 (3슬롯)
  - 통은 1/2/3 유닛 폭. 상단 플랜지를 틀 테두리 위에 걸치는 drop-in
  - 후크 인터페이스는 cutlery_holder 에서 검증된 더브테일 그대로

좌표 규약 (조립 기준):
  - 틀 개구 중심 = 원점(XY), z=0 틀 바닥, +Z 위
  - -Y = 박스쪽(뒷면). 틀 뒷면이 박스 바깥면쪽, 후크가 테두리를 감쌈.
"""

# ---- 유닛 / 틀 ----
UNIT = 70.0                       # 기본 유닛 (X 폭 = Y 깊이)
SLOTS = 3                         # 틀 수용 유닛 수
OPEN_W = UNIT * SLOTS             # 210 틀 내부 개구 X
OPEN_D = UNIT                     # 70  틀 내부 개구 Y
FRAME_WALL = 4.0                  # 틀 벽 (앞/좌/우) — 플랜지가 얹히는 시트
BACK_WALL = 12.0                  # 틀 뒷벽 — 더브테일 슬롯(깊이 7.1)을 벽 안에 품음
FRAME_H = 40.0                    # 틀 높이 (테두리 깊이)
OUT_W = OPEN_W + 2 * FRAME_WALL   # 218 (베드 256 안)
Y_FRONT = OPEN_D / 2 + FRAME_WALL     # +39 틀 앞면
Y_BACK = -(OPEN_D / 2 + BACK_WALL)    # -47 틀 뒷면 (박스쪽)

# ---- 통 (bin) — build_bin(units, height) 로 폭/높이 가변 ----
BIN_CLR = 0.5      # 통 몸통 ↔ 개구, 축당 총합 (사용자 확정: drop-in 넉넉히)
BIN_WALL = 2.0     # 통 벽
BIN_BASE = 2.4     # 통 바닥
FLANGE_T = 3.0     # 플랜지 두께
FLANGE_D = OPEN_D + 2 * FRAME_WALL   # 78 플랜지 Y 폭 (틀 앞벽 바깥과 면일치)
# X 방향 플랜지는 몸통과 면일치 (이웃 통과 간섭 방지). 하중은 앞/뒷벽이 받음.
FRAME_CH = 3.0     # 틀 개구 위 모서리 45° 챔퍼 — 통 플랜지 챔퍼(4.25)와 맞물려
                   # 안착(self-centering) + 삽입 깔때기. 통은 이 챔퍼면에 얹힘.

# ---- 유닛 경계 리브/홈 (X 위치 고정 + 덜그럭 방지) ----
# 틀 앞/뒷벽 안쪽면의 유닛 경계(x=±35)에 세로 리브. 통은 모든 70mm 경계
# 위치의 앞/뒤 바깥면에 세로 홈 — 어떤 폭 통이든 리브와 간섭 없이 물림.
RIB_W = 4.0                  # 리브 폭 (X)
RIB_P = 1.2                  # 리브 돌출 (Y) — 깊게 물려 확실히 걸림
RIB_CLR = 0.2                # 리브 ↔ 홈 폭 공차 (사용자 확정: X 유격 ±0.1)
RIB_TAPER = 6.0              # 리브 상단 테이퍼 구간 (삽입 유도)
RIB_TOP = FRAME_H - 4.0      # 36 — 안착한 플랜지 챔퍼(≥36.75)와 간섭 없게
GROOVE_W = RIB_W + RIB_CLR   # 4.4 홈 폭
GROOVE_D = RIB_P + 0.3       # 1.1 홈 깊이 (리브보다 깊게 — 폭으로만 물림)

# ---- 더브테일 인터페이스 (cutlery_holder 검증값 그대로) ----
DT_W = 20.0        # 안쪽 넓은 폭 (= HOOK_WIDTH)
DT_NECK = 12.0     # 목(입구) 폭
DT_DEPTH = 4.0     # 경사 깊이 (45°)
DT_SEAT = 3.0      # 넓은 끝 직사각형 seat
DT_CLR = 0.1       # 암/수 클리어런스
BACK_CLR = 0.3     # 틀 뒷면 ↔ 후크 보강판 여유

# ---- 후크 (별도 부품 3개, 옆으로 뉘여 출력) ----
HOOK_XS = (-75.0, 0.0, 75.0)
HOOK_WIDTH = 20.0
BOX_WALL = 18.0    # 박스 상단 테두리 두께 (실측)
HOOK_CLR = 0.6
HOOK_T = 4.0       # 보강판/안쪽 하강 살 두께
CLAMP_T = 2.5      # 걸이 브릿지 살 (인장 부하라 얇게)
HOOK_DROP = 84.0
FLARE = 3.0
FLARE_LEN = 10.0
HOOK_RISE = 54.0   # 후크 상단이 틀 상단보다 위 — 후크 최상단→바스켓(H160)
                   # 바닥 210mm (틀이 박스 테두리에서 그만큼 내려와 걸림)

# ---- 틀 뒷벽 슬롯 ----
SLOT_TOP = FRAME_H - 10.0   # 30 레일 상단 = 틀 무게 지지 높이
