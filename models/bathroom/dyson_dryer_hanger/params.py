RIB_TOP_Z = SLOT_H + ARM_T                   # 리브 최상단

# ---- 연결 방식: 십자 맞춤 (cross-lap) ----
# 도브테일도 접착제도 쓰지 않는다. 서로 홈을 파 맞물리게 하되
# **하중/중력이 맞물림을 눌러 앉히는 방향**으로 배치한다.
#
#   A : 선반 위. 리브 위팔에 위로 열린 홈, 커넥터에 아래로 열린 홈 → 위에서 눌러 끼움.
#       위로 밀어 올릴 힘이 없어 자기 무게로 유지된다.
#   B : 리브 최하단 **뒤쪽 돌기** + 보. 돌기 위는 완전히 비어 있어 보를 위에서
#       떨어뜨려 건다. 보가 돌기에 얹혀 중력으로 유지된다.
#       (스파인에 직접 붙이려 했을 땐 위를 아래팔이 막아 이 방식이 불가능했다)

