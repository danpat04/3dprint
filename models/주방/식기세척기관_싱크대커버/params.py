"""식기세척기관_싱크대커버 — 공통 파라미터.

좌표계:
  원점 = 구멍 중심 × **상판 윗면**
  x : 관이 기울어 나가는 방향 (+x = 보울 바깥쪽)
  z : 위 — 상판이 z 0 ~ -1 을 차지

구조:
  ① cover  상판 위 플랜지(아랫면에 오링 홈) + 비스듬한 목 + 구멍을 지나는 칼라
  ② nut    칼라에 **아래에서** 끼워 올려 조인다. 상판을 사이에 물고 오링을 누른다

**여유가 1.57mm 뿐인 설계다.** 두 관을 맞붙인 최소 외접원이 28.35 이고 구멍이
31.5 다. 그래서:
  - 두 통로 사이에 벽을 못 세운다 → **8 자 한 공동**
  - 칼라 바깥벽이 1.1mm 뿐 → 나사산을 **0.4mm 얕게** 판다
  - **구멍 안에서는 관을 기울일 수 없다.** 비스듬히 자르면 단면이 28.8/cos θ
    로 커져 10도만 기울여도 31.4 가 된다. 기울임은 상판 위 목에서만 한다
"""

# ---- 실측 ----
HOLE_D = 31.5          # 상판 구멍 (옛 터치 스위치 자리)
DECK_T = 1.0           # 상판 금속 두께 — 얕은 스테인리스
DRAIN_D = 22.0         # 배수관 바깥지름
SUP_D = 6.35           # 급수관 바깥지름 (1/4")

# ---- 관 통로 — **큰 원 하나** ----
# 8 자로 딱 맞게 파지 않는다. 배수 호스 한쪽 끝에 ⌀25.5 로 굵어지는 부분이
# 있어서 두 관을 동시에 통과시킬 수 없기 때문이다.
# 굵은 쪽(25.5)을 먼저 넣고 그다음 급수관(6.35)을 끼운다.
DRAIN_FAT_D = 25.5     # 배수 호스 끝 굵은 부분 (실측)
BORE_D = 28.5          # 한 개의 큰 보어
# 근거 ①: ⌀22 와 ⌀6.35 를 함께 담는 **최소 원이 28.35** → 28.5 면 둘 다 들어간다
# 근거 ②: 굵은 부분 25.5 에 3.0 여유로 통과한다
# 근거 ③: 칼라 바깥 31.0 에서 벽 1.25 가 남는다 — 구멍 31.5 를 지나는 한계치

# ---- 칼라 (구멍을 지나는 부분) ----
COLLAR_OD = 31.0       # 구멍 31.5 에 한쪽 0.25
COLLAR_WALL = (COLLAR_OD - BORE_D) / 2   # 1.25 — 여기가 전부다
COLLAR_LEN = 13.0      # 상판 아래로 내려가는 길이 (너트가 물 자리)
COLLAR_PILOT = 2.0     # 맨 위 ⌀31.0 구간 — 구멍 안에서 중심을 잡아준다

# 나사산 — 벽이 1.25mm 뿐이라 **얕게** 판다.
# 골지름 30.2 기준 남는 살 (30.2-28.5)/2 = 0.85mm.
# 하중은 오링 누르는 60N 정도라 인장 1.3 MPa, 강도는 문제가 아니다
THREAD_PITCH = 2.0
THREAD_DEPTH = 0.4
THREAD_LEN = 9.0       # 조임 행정 = 4.5 바퀴. 상판 두께가 1 안팎이라 넉넉히 둔다
THREAD_GAP = 1.0       # 파일럿과 나사 사이 빈 구간.
                       # 0 으로 두면 나사 꼭대기(⌀31.0)가 파일럿(⌀31.0)과
                       # **정확히 접해** 불린이 Null 을 뱉는다
THREAD_FIT = 0.2       # 너트와의 여유 (반지름 방향)
THREAD_EMB = 0.2       # 나사산 뿌리를 칼라 속에 묻는 양.
                       # 0 이면 뿌리가 칼라 표면과 정확히 일치해 접선 불린이
                       # 되고 OCC 가 Null 을 뱉는다
COLLAR_ROOT = COLLAR_OD - 2 * THREAD_DEPTH    # 30.2 — 나사 골지름

# ---- 플랜지 (상판 위에 앉는 판) ----
FLANGE_D = 54.0        # 오링 굵기 3.5 를 쓰게 되어 홈이 ⌀46.05 까지 나간다.
                       # 바깥 테두리 4mm 를 남기려면 ⌀54 가 필요하다
FLANGE_T = 6.0         # 홈이 2.66 깊어져 최소 단면이 두께−홈깊이 다.
                       # 5 면 유효 2.34 로 15.4 MPa, 6 이면 3.34 로 7.6 MPa
FLANGE_R = 1.5         # 윗 모서리 라운드

# 칼라–플랜지 이음이 **가장 빠듯한 곳**이다. ⌀31 에서 ⌀46 으로 꺾이는 직각 턱에
# 조임 인장이 집중되고, 세워 뽑으므로 그 인장이 층을 가로지른다.
# 공칭 5.1 MPa 에 집중 3 배면 15 MPa, 층간 강도 30 의 절반까지 올라간다.
# 릴리프를 파서 그 안에 필렛을 넣으면 8 MPa 로 내려간다 (여유 3.8 배).
# 릴리프는 오링 홈 안쪽 가장자리(⌀35.9)를 침범하지 않아야 한다
CHAM_D = 34.0          # 칼라–플랜지 이음을 **45도 모따기**로 푼다.
                       # 필렛을 쓰려 했으나 릴리프 안쪽이 칼라와 정확히 접해
                       # 모서리가 안 생겨 필렛이 안 걸렸고, 깔때기와 겹쳐
                       # 살을 0.6mm 로 깎기까지 했다.
                       # 모따기는 집중계수를 3 → 1.8 로 낮추고(15 → 9 MPa),
                       # 45도라 칼라를 아래로 두고 뽑을 때 **자기지지**다.
                       # 상판에 닿는 면은 ⌀34~54. 오링 홈(⌀36.95~46.05) 안쪽에
                       # 벽이 1.48mm 남는다 (⌀35 면 0.98 로 얇았다)

# ---- 오링 (내경 35 × 굵기 2.5 실리콘) ----
ORING_ID = 38.0        # **사용자 보유 오링**: 내경 38 일 때 굵기가 3.5 다
ORING_CORD = 3.5       # 보유품 실측. 홈 폭·깊이가 여기서 따라 나온다
ORING_MEAN = ORING_ID + ORING_CORD       # 37.5 — 홈 중심 지름
ORING_W = ORING_CORD * 1.3               # 3.25 — 홈 폭
ORING_DEPTH = ORING_CORD * 0.76          # 1.90 — 눌림 24%
# 홈 안쪽 가장자리 ⌀35.9 > 구멍 31.5 → 단단한 상판 위에 앉는다

# ---- 엘보 (상판 위, 관을 옆으로 꺾어 내보낸다) ----
# 사용자 피드백: 구스넥처럼 꺾어 관이 옆으로 나가게.
# 효과가 둘이다 — 호스가 **받쳐진 채** 꺾여 자유 굽힘보다 덜 꺾이고,
# 출구가 옆을 보므로 위에서 떨어지는 물이 입으로 안 들어간다.
#
# 꺾으려면 반드시 올라가야 한다: 올라가는 높이 = ELBOW_R x sin(각도).
# 반경을 줄이면 낮아지지만 호스가 꺾인다. 22 호스는 보통 R/D >= 2 (R >= 45),
# 주름관이면 훨씬 작아도 된다.
ELBOW_R = 22.0         # 중심선 곡률반경. R/D = 1.00 — **주름관이라 가능한 값**.
                       # 매끈한 관이면 R>=45 라 높이가 54mm 가 된다
ELBOW_TURN = 60.0      # 도. 출구가 수평에서 30도 위를 본다
                       # 그 이상 꺾어도 **높아지지 않고** 출구만 수평에 가까워진다
ELBOW_BORE = 33.0      # 엘보 구간 보어. 칼라(28.5)보다 **크게** 한다.
                       # 엘보는 상판 위라 구멍 31.5 제약을 안 받는다.
                       # 휜 보어를 지나려면 25.5 + L²/(8R) 이어야 하는데
                       # 33 이면 굵은 부분 길이가 38mm 까지 통과한다 (28.5 는 24mm)
ELBOW_RAMP = 0.3       # 보어가 28.5 → 33 으로 벌어지는 구간 (높이비)
NECK_WALL = 2.0
MOUTH_FLARE = 2.5      # 출구 나팔 — 꺾이는 지점에 날카로운 모서리를 없앤다

# ---- 너트 ----
NUT_OD = 42.0
NUT_H = 9.0
NUT_FLUTES = 8         # 손으로 돌릴 홈
NUT_FLUTE_R = 3.5
