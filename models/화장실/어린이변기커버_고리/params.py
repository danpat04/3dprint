"""어린이변기커버_고리 — 공통 파라미터.

좌표계:
  원점 = 핀 축 × **고리판의 아랫면**(커버에 닿는 면)
  x : 고리가 뻗어나가는 방향 (+x 가 커버 바깥)
  y : 받침판이 밀려 들어오는 방향 (+y 에서 −y 로 민다)
  z : 위 — 고리판이 z 0~5, 커버가 z 0~−5 를 차지

부착 방식은 **홈 + 슬라이드 받침판** 이다. 마감 뚜껑까지 4 파츠.
  ③ 핀을 ① 고리판과 커버 구멍(6.6)에 위에서 꽂는다 (맨 아래 턱의 팔각 외접이
     6.26 이라 그대로 지나간다).
  ② 받침판을 커버 밑에서 **옆으로 밀어** 핀의 홈에 끼운다.
  홈이 밀어 넣는 방향으로 좁아지는 **쐐기**라 밀수록 조인다.

휘는 부품이 하나도 없다. 당기는 힘은 핀의 아래 턱이 받침판 턱을 밀어 올리는
순수 형상 접촉이라 크리프·영구변형과 무관하다.

**왜 외팔보 스냅을 버렸나:** 커버 구멍 6.6 이 날 폭을 5.6 으로 묶고,
"홈 + 갈래 2 개 = 5.6" 이라 갈래를 두껍게 하면 오므라들 거리가 없고, 거리를
주면 갈래가 0.9mm 로 얇아져 인장 한계에 닿는다. 물림도 카운터보어가 천장이라
1.45 에서 안 올라간다. 네 번 출력해 세 번 실패한 근본 원인이 이 천장이었다.
"""

# ---- 커버 (실측) ----
HOLE_D = 6.6           # 기존 구멍 — 관통
COVER_T = 5.0          # 구멍 자리의 커버 두께
EDGE_DIST = 15.0       # 구멍 중심에서 커버 바깥 가장자리까지 (사용자: 15 이하)

# ---- 고리판 ① (이전 출력물을 그대로 쓴다) ----
PLATE_T = 5.0          # 판 두께. 3mm 는 면 밖 굽힘에 약해 5 로 올렸다
PLATE_BORE = 6.5       # 날(외접 6.26)이 지나는 구멍 — 유격 한쪽 0.13
PLATE_CB_D = 9.6       # 핀 머리 자리 (머리 팔각 외접 9.23)
PLATE_CB_T = 2.0       # 머리가 윗면에 묻히는 깊이
DISC_D = 16.0          # 핀 둘레의 원반
NECK_W = 12.0          # 목 폭 — 여기가 최소 단면이다
RING_CTR = 32.0        # 핀에서 고리 중심까지
RING_ID = 28.0         # 고리 안지름 — 3~5mm 후크를 겨누기엔 기존 6.6 의 4 배다
RING_OD = 42.0
# 고리 구멍은 x = 18 ~ 46 을 차지한다. 가장자리가 최악(15)이어도 3mm 비켜 있어
# 후크가 커버에 쓸리지 않는다. 고리 살은 커버 위에 걸쳐도 무방하다
EDGE_R = 1.5           # 판 **윗** 둘레 라운드 — 손가락이 닿는 면
EDGE_CH = 1.2          # 판 **아랫** 둘레 모따기. 이 면이 bed 라 라운드면 처진다

# ---- 관통 핀 ③ (별도 파츠 — **눕혀서** 출력한다) ----
BLADE_W = 5.6          # 날 폭 (조립 좌표 x)
BLADE_T = 5.6          # 날 두께 (조립 좌표 y) = 눕혔을 때의 출력 높이
BLADE_CH = 1.4         # 45도 모따기 → 팔각. 외접 6.26 으로 구멍 6.6 을 거의 채운다
PIN_HEAD_W = 8.8       # 고리판 윗면 카운터보어에 앉는다 (팔각 외접 9.23 < 9.6)
PIN_HEAD_T = 2.0

GROOVE_D = 3.6         # 홈 바닥 지름 — 받침판 슬롯이 여기에 물린다
GROOVE_H_OPEN = 2.10   # 받침판이 들어오는 쪽(+y)의 홈 높이
GROOVE_H_END = 1.75    # 다 밀어 넣은 쪽(−y)의 홈 높이
                       # **쐐기다.** 밀수록 조여 축 유격이 0 이 된다.
                       # 경사 0.35/5.6 = 3.6도 < 마찰각 17도 → 자기잠김, 안 풀린다.
                       # 받침판 두께 편차 ±0.15 도 이 범위가 흡수한다

# ---- 받침판 ② (U 자 슬롯 — 옆에서 밀어 끼운다) ----
BASE_D = 20.0          # ⌀16 이었으나 스프링 핑거를 길게 쓰려고 키웠다.
                       # 커버 아래라 안 보이는 자리다
BASE_T = 3.0
BASE_SLOT_W = 3.8      # 홈(3.6)에 한쪽 0.1
BASE_LEDGE_T = 1.8     # 슬롯이 난 윗 구간. 핀의 아래 턱이 이 면을 밀어 올린다
BASE_RECESS_W = 7.6    # 아래 구간 — 턱(팔각 외접 6.26)이 지나는 통로.
                       # 턱보다 넉넉하게 잡아 핑거 폭을 벌었다
BASE_R = 0.5           # 아래 모서리 라운드. 뚜껑 치마가 잡을 옆면을 남기려고
                       # 1.0 에서 줄였다 (라운드만큼 잡을 데가 사라진다)

# 걸림 돌기와 스프링 핑거.
# 돌기는 **하중을 받지 않는다.** 커버 무게는 핀의 아래 턱이 받침판 턱을
# 밀어 올리는 경로로 가고, 돌기는 받침판이 옆으로 빠지는 것만 막는다.
#
# 통원반은 안 휘므로 릴리프 슬롯을 파서 양쪽을 외팔보로 만든다.
# **릴리프 안쪽 끝 = 아래 통로 벽(BASE_RECESS_W/2)** 으로 맞춘다.
# 어긋나면 그 사이에 0.2mm 짜리 얇은 벽이 남는데, 역할도 없고 출력도 안 된다.
RELIEF_W = 1.0
RELIEF_X = BASE_RECESS_W / 2 + RELIEF_W / 2    # 4.3 — 안쪽 끝이 통로 벽과 일치
RELIEF_END = -7.3      # 릴리프 안쪽 끝 = 핑거의 뿌리. 돌기까지 8.5mm 외팔보

DETENT_H = 0.5         # 돌기가 슬롯 안으로 튀어나오는 양 (한쪽).
                       # 0.2 는 0.4 노즐의 압출폭보다 작아 슬라이서가 뭉갠다.
                       # 최소 한 압출폭 이상이어야 형상이 살아난다
DETENT_Y = 1.2         # 돌기 위치 — 핀 기둥(반지름 1.8)이 지나간 **뒤쪽**
# 램프를 넘는 축방향 힘은 N·tan(경사각) 이다. 경사가 **급할수록 힘이 커진다.**
# 그래서 들어오는 쪽은 완만하게(쉽게 들어가고), 나가는 쪽은 급하게(잘 안 빠지게).
DETENT_RAMP_IN = 0.87  # 30도 — 밀어 넣는 쪽
DETENT_RAMP_OUT = 0.29  # 60도 — 빠지는 쪽. 직각으로 두면 영구 고정이라
                       # 분해가 불가능해지므로 경사를 남긴다

# ---- 마감 뚜껑 ④ (기능 없음, 미관용) ----
# 받침판의 U 슬롯·릴리프가 겉으로 드러나 보기 싫다는 피드백.
# 받침판 옆면(⌀20)을 치마로 잡는 얕은 컵이다. 받침판 설계는 건드리지 않는다.
LID_FIT = 0.1          # **간섭** (지름 기준). 치마 안지름이 ⌀20 보다 0.1 작다.
                       # 마찰로만 잡는다 — 사용자 요청. 안 들어가면 0.0,
                       # 헐거우면 0.2 로 조정한다
LID_WALL = 0.75        # 치마 살 두께
LID_FLOOR = 1.0        # 바닥 — 커버 아래로 **이만큼만** 더 나온다 (3.0 → 4.0)
LID_SKIRT = 2.2        # 치마 높이 = 받침판을 물고 올라가는 길이
LID_LEAD = 0.4         # 입구 모따기 — 겨누기 쉽게

# ---- 조립 좌표 ----
GROOVE_TOP = -COVER_T                    # −5.0  홈 윗면 = 커버 아랫면
BOSS_BOT = GROOVE_TOP - BASE_T           # −8.0  핀 맨 아래 = 받침판 아랫면
PIN_SHANK_TOP = PLATE_T - PLATE_CB_T     #  3.0  머리 밑면
# 커버 아래로 튀어나오는 높이 = 받침판 3.0 + 마감 뚜껑 바닥 1.0 = 4.0
